"""Generate 起航小车_引脚映射.md (v2.1, SkyStar only, plan C) and qh_core_pinmap.h from pinmap_sky.json."""
import json, sys, os

OUT = sys.argv[1]
d = json.load(open(os.path.join(os.path.dirname(__file__), 'pinmap_sky.json'), encoding='utf-8'))
sock = {int(k): v for k, v in d['sock'].items()}
rev = {v: k for k, v in sock.items()}
m, reserved, spare = d['map'], d['reserved'], d['spare']
by_gpio = {v[0]: n for n, v in m.items()}

GROUPS = [('下板', '经叠板连接器 J603 到下板'), ('板内 I2C', '板内 I2C1 总线'), ('串口座', '串口座（XH-4P：5V / TX / RX / GND）'),
          ('I2C 座', 'I2C 座（SH1.0 4P Qwiic：GND / 3V3 / SDA / SCL）'), ('灰度', '灰度传感器（6 路 ADC）'), ('E01', 'E01 无线（SPI1）'),
          ('IMU', '姿态模块'), ('交互', '人机交互')]

L = []
L.append('# 起航小车引脚映射 v2.1（只用天空星 STM32F407，方案 C）\n')
L.append('> 日期：2026-11-01　方案 C：J603.38 保持 NC，下板 J513.37 保留 IMON；替代 v2.0 引脚分配。v1.0（天空星 / 天猛星双核心板）存为 [起航小车_引脚映射_v1_双核心板.md](起航小车_引脚映射_v1_双核心板.md)')
L.append('> 核心板：立创·天空星 STM32F407VET6 / VGT6。插座位置 S1–S40 = 天空星 P1 第 n 脚，S41–S80 = P2 第 n 脚（立创 wiki「双路 80PIN 排针」原理图）')
L.append('> 复用功能已逐条对照天空星官方引脚定义图核对。生成脚本：`pinmap_sky.py` → 本文件 + `qh_core_pinmap.h`\n')
L.append('## 1. 结论\n')
L.append(f'- 共 {len(m)} 路信号，全部直连天空星排针，**不再需要 TMUX1574 切换和板型识别**')
L.append('- 6 路串口全部用上：UART4 给下板步进驱动器，其余 5 路（USART1/2/3/6、UART5）各一个 XH-4P 座；DAP 调试串口插 USART1 的 J619 座')
L.append('- 3 路 I2C 全部引出：I2C1 是板内总线（OLED、JY901S、EEPROM、下板 INA228/TCA9555），同时引一个 Qwiic 座；I2C2、I2C3 各一个 Qwiic 座')
L.append('- 6 路灰度全部接 ADC，按键、旋钮、蜂鸣器、RGB 灯改为直连 MCU（上板 TCA9555 删除；下板 TCA9555 0x21 不变）')
L.append(f'- 空余引脚：{", ".join(spare)}（PC1–PC3 可作 ADC）\n')
L.append('## 2. 天空星板载外设占用（不能随意使用的脚）\n')
L.append('| 引脚 | 板载用途 | 本设计的处理 |\n|---|---|---|')
L.append('| PA0 | 用户按键（10k 串阻 + 10k 下拉） | 不接 |')
L.append('| PA4 | SPI Flash 片选（10k 上拉；高配版贴 W25Q128，青春版不贴） | 不接；固件把 PA4 设为输出高，E01 与 Flash 共用 SPI1 |')
L.append('| PA5 / PA6 / PA7 | SPI Flash 总线（经 0Ω 排阻） | 作 E01 的 SPI1 |')
L.append('| PC8–PC12、PD2 | TF 卡 SDIO（经 0Ω 排阻，各有 47k 上拉） | 不用板载 TF 卡；改作 E01_CS、UART4（下板步进总线）、UART5 和 I2C3。47k 上拉对串口和 I2C 无影响 |')
L.append('| PD3 | TF 卡插入检测（47k 上拉） | 不用板载 TF 卡；改作 E01_CE |')
L.append('| PA9 / PA10 | USART1，只在核心板调试缺口上 | 不用；USART1 改用 PB6/PB7 引座 |')
L.append('| PB2 | 用户 LED（BOOT1） | 没引到排针 |')
L.append('| PA13 / PA14、PA11 / PA12、PC14 / PC15、PH0 / PH1 | SWD、USB、晶振 | 没引到排针 |\n')
L.append('## 3. 按功能分组\n')
for g, title in GROUPS:
    rows = [(n, v) for n, v in m.items() if v[2] == g]
    if not rows: continue
    L.append(f'### {title}\n')
    L.append('| 网络 | 引脚 | 插座位置 | 功能 | 说明 |\n|---|---|---|---|---|')
    for n, (gp, fn, _, note) in rows:
        L.append(f'| `{n}` | {gp} | S{rev[gp]} | {fn} | {note} |')
    L.append('')
L.append('## 4. 插座逐脚表\n')
L.append('| 插座 | 引脚 | 网络 | | 插座 | 引脚 | 网络 |\n|---|---|---|---|---|---|---|')
def cell(s):
    p = sock[s]
    if p in by_gpio: return f'S{s} | {p} | `{by_gpio[p]}`'
    if p in reserved: return f'S{s} | {p} | 不连（{reserved[p].split("（")[0]}）'
    if p in ('5V',): return f'S{s} | 5V | `5V_MAIN`'
    if p in ('GND', 'AGND'): return f'S{s} | {p} | `GND`'
    if p in ('3V3', 'VREF', 'BAT'): return f'S{s} | {p} | 不连'
    return f'S{s} | {p} | 空余'
for i in range(1, 41):
    L.append(f'| {cell(i)} | | {cell(i + 40)} |')
L.append('\n## 5. 固件注意事项\n')
L.append('1. 上电初始化先把 PA4 设为推挽输出高（高配版板载 Flash 片选），再配置 SPI1 给 E01')
L.append('2. PA15、PB4 复位后是 JTAG 脚，使用前只保留 SWD（HAL 默认 SWD 模式即可释放）')
L.append('3. TIM1 4 个通道驱动两路 DRV8870，频率 20 kHz；TIM4 4 通道 50 Hz 驱动舵机；TIM9、TIM12 分别给两路步进发脉冲')
L.append('4. 编码器：左轮 TIM3（16 位，必须处理溢出），右轮 TIM2（32 位）；右轮 A/B 相对 v2.0 对调，左右方向都需实测')
L.append('5. 按键 KEY1–KEY5、EC11_P 用内部上拉，低电平有效；EC11_A/B 已有外部 10k 上拉 + 10nF')
L.append('6. 下板 TCA9555（0x21）仍控制步进 DIR/EN 等，中断改接 PE10（EXTI10）')
L.append('7. TIM1 只使用 CH1–CH4 主输出，所有 CHxN/BKIN 保持关闭；IOX_INT=PE10、MOT_EN=PE12 虽落在 CH1N/CH3N 脚，但只作 GPIO')
L.append('8. EXTI13 由 IMU_INT=PB13 与 KEY5=PC13 共用，EXTI10 由 IOX_INT=PE10 与 EC11_P=PD10 共用；KEY5、EC11_P 采用轮询，不配置对应 EXTI')
open(OUT, 'w', encoding='utf-8').write('\n'.join(L) + '\n')

H = ['/* qh_core_pinmap.h - generated by pinmap_sky.py, SkyStar STM32F407 only (v2.1, plan C) */', '#pragma once', '']
for n, (gp, fn, g, note) in m.items():
    port, num = gp[1], int(gp[2:])
    H.append(f'#define QH_{n:<10s} GPIO{port}, GPIO_PIN_{num:<2d} /* {fn}{" - " + note if note else ""} */')
open(os.path.join(os.path.dirname(OUT), 'qh_core_pinmap.h'), 'w', encoding='utf-8').write('\n'.join(H) + '\n')
print('ok', len(m))
