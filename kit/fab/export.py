"""Export the fabrication set of one board from EasyEDA into a release folder, plus a project backup.

usage: python export.py [out_dir]          (default: <config dir>/release/<board>_<yyyymmdd-HHMM>)
Writes: Gerber zip (copper, mask, paste, silkscreen, outline, drill), pick-and-place CSV, BOM CSV,
IPC-D-356A netlist (bare-board electrical test), and <name>_project.epro2 (whole-project backup).
Then run check.py on the folder. Ordering stays manual: this script never calls the place*Order APIs.

Each file is generated by eda.pcb_ManufactureData and handed back base64-encoded through `debug exec`, then
written here: eda.sys_FileSystem.saveFileToFileSystem refuses arbitrary paths ("路径不允许") and is disabled on
clients that are not fully offline. Prerequisite: DRC 0, conn.py 0 open nets, PCB saved.
"""
import base64, json, os, sys, time
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import common as K

B = K.board()
out = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else
                      B.path(os.path.join('release', f"{B.name}_{time.strftime('%Y%m%d-%H%M')}")))
os.makedirs(out, exist_ok=True)
name = B.fab.get('name', B.name)
U = "((typeof ESYS_Unit !== 'undefined') ? ESYS_Unit.MILLIMETER : undefined)"
JOBS = [  # (key, JS expression producing a File, extension to enforce)
    ('gerber', f"eda.pcb_ManufactureData.getGerberFile({json.dumps(name + '_Gerber')}, false, {U})", '.zip'),
    ('cpl', f"eda.pcb_ManufactureData.getPickAndPlaceFile({json.dumps(name + '_PickAndPlace')}, 'csv', {U})", '.csv'),
    ('bom', f"eda.pcb_ManufactureData.getBomFile({json.dumps(name + '_BOM')}, 'csv')", '.csv'),
    ('ipc356', f"eda.pcb_ManufactureData.getIpcD356AFile({json.dumps(name + '_IPC356A')})", ''),
]
missing = []
for key, expr, ext in JOBS:
    code = (f"const f = await {expr}; if (!f) return null; const b = new Uint8Array(await f.arrayBuffer()); "
            "let s = ''; for (let i = 0; i < b.length; i += 0x8000) s += String.fromCharCode.apply(null, b.subarray(i, i + 0x8000)); "
            "return {name: f.name, size: b.length, b64: btoa(s)};")
    try:
        v = K.js(code, timeout=300)
    except SystemExit as e:
        v = None; print(f'{key:8} FAILED', str(e)[:200])
    if not v:
        missing.append(key); print(f'{key:8} NOT EXPORTED'); continue
    data = base64.b64decode(v['b64'])
    fn = v['name'] if not ext or v['name'].lower().endswith(ext) else v['name'] + ext
    open(os.path.join(out, fn), 'wb').write(data)
    ok = len(data) == v['size'] and len(data) > 0
    if not ok: missing.append(key)
    print(f'{key:8} {fn}  {len(data)} bytes' + ('' if ok else '  SIZE MISMATCH'))

# whole-project backup next to the fabrication files (the archive is what restores the design later)
backup = os.path.join(out, f'{name}_project.epro2')
r = K.export_project(backup)
print('backup  ', os.path.basename(backup) if r.get('ok') else 'FAILED ' + json.dumps(r.get('error'), ensure_ascii=False)[:200])
if not r.get('ok'): missing.append('backup')
print('->', out)
print('next: python check.py', out)
sys.exit(1 if missing else 0)
