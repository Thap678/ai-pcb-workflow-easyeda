"""MCU pin map as code: the single source for the pin document, the firmware header and the schematic specs.

Copy next to your specs and fill SOCKET / MAP / RESERVED / AF. Run it after every change:
    python pinmap.py            -> checks + pinmap.json + pinmap.md + pinmap.h
Checks: duplicate pins, pins not on the socket / package, functions the pin does not have (when AF lists the pin),
EXTI line clashes (STM32: EXTI line = pin number), reserved pins used. A real example (STM32F407 core board on an
80-pin socket, 62 signals): examples/nuedc-car-2026/inputs/pinmap_sky.py.
"""
import collections, json, os, re

# Socket / package position -> pin name. For a core-board socket use the board's BOTTOM view, as it plugs in.
SOCKET = {1: 'PA0', 2: 'PA1', 3: 'PA2', 4: 'PA3', 5: 'GND', 6: '3V3'}          # <- fill in

# signal net: (pin, function, group, note). function: 'USART1_TX', 'TIM1_CH1', 'ADC1_IN3', 'GPIO', 'GPIO EXTI5' ...
MAP = {
    'U2_TX': ('PA2', 'USART2_TX', 'serial', ''),                                 # <- fill in
    'LED': ('PA3', 'GPIO', 'hmi', ''),
}

# pins the board itself already uses (boot pins, on-board LED/flash/button, debug port): never assign them
RESERVED = {'PA0': 'on-board user button'}

# optional: pin -> functions it supports (from the datasheet AF table). Pins missing here are not checked.
AF = {'PA2': ['USART2_TX', 'TIM2_CH3', 'ADC1_IN2', 'GPIO'], 'PA3': ['USART2_RX', 'TIM2_CH4', 'ADC1_IN3', 'GPIO']}

if __name__ == '__main__':
    here = os.path.dirname(os.path.abspath(__file__))
    on_socket = set(SOCKET.values())
    pins = collections.Counter(v[0] for v in MAP.values())
    dup = [p for p, n in pins.items() if n > 1]
    off = [s for s, v in MAP.items() if v[0] not in on_socket]
    bad_af = [s for s, (p, f, _, _) in MAP.items() if p in AF and f.split()[0] not in AF[p]]
    exti = collections.Counter(int(re.sub(r'\D', '', v[0][2:])) for v in MAP.values() if 'EXTI' in v[1])
    clash = [line for line, n in exti.items() if n > 1]
    reserved = [s for s, v in MAP.items() if v[0] in RESERVED]
    spare = sorted(p for p in on_socket if re.match(r'P[A-Z]\d+$', p) and p not in pins and p not in RESERVED)
    print(f'signals {len(MAP)} | duplicate {dup} | not on socket {off} | wrong function {bad_af} | '
          f'EXTI clash {clash} | reserved used {reserved}')
    print('spare', spare)
    json.dump({'socket': SOCKET, 'map': MAP, 'reserved': RESERVED, 'spare': spare},
              open(os.path.join(here, 'pinmap.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    by_pin = {v[0]: s for s, v in MAP.items()}
    md = ['| 插座 | 引脚 | 信号 | 功能 | 分组 | 说明 |', '|---|---|---|---|---|---|']
    for pos, pin in sorted(SOCKET.items()):
        s = by_pin.get(pin)
        md.append(f'| {pos} | {pin} | {s or ""} | {MAP[s][1] if s else RESERVED.get(pin, "")} | '
                  f'{MAP[s][2] if s else ""} | {MAP[s][3] if s else ""} |')
    open(os.path.join(here, 'pinmap.md'), 'w', encoding='utf-8').write('\n'.join(md) + '\n')
    h = ['#pragma once', '/* generated by pinmap.py - do not edit */']
    for s, (p, f, g, n) in MAP.items():
        port, num = p[1], re.sub(r'\D', '', p[2:])
        h.append(f'#define PIN_{s:<12} GPIO{port}, GPIO_PIN_{num:<3} /* {f} {n} */')
    open(os.path.join(here, 'pinmap.h'), 'w', encoding='utf-8').write('\n'.join(h) + '\n')
    raise SystemExit(1 if (dup or off or bad_af or clash or reserved) else 0)
