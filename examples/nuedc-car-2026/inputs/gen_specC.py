"""Build full-page specs for the rebuilt project (2026-11-03) with Plan C applied.

Inputs: v2 page specs n1/n1_imu/n2..n5 (upper) and p1..p6 (lower), pinmap_sky.json (Plan C, regenerated by
pinmap_sky.py), route/swap_c.json (J603 slots, UART destinations, Qwiic / pull-up assignment).
Writes ../specs/c_u1..c_u5.json and c_l1..c_l6.json for kit/sch (project / page UUIDs below: replace them
with your own project's when you rebuild this example).
"""
import json, os, copy
HERE = os.path.dirname(os.path.abspath(__file__))
L = lambda f: json.load(open(os.path.join(HERE, f), encoding='utf-8'))
def save(f, d): json.dump(d, open(os.path.join(HERE, '..', 'specs', f), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)

P = '5be68595f2b413c75a7f2937434f239f53e66b44c02f15a2e2e3494fe05d691c'
UP = ['3f56972e35c2111e', '9c1e217877da67e8', '326055d4a195df5b', '94f0246b63b42101', '1a6e30b87c3e92d4']
LO = ['a5774013b576f21f', '6d3d2ce8ad7f18eb', 'ea7e88c767152ac3', 'a389946372ee92b0', '84bc5a0ab7272c51', '0db7f10ac778306b']
pm = json.load(open(os.path.join(HERE, 'pinmap_sky.json'), encoding='utf-8'))
C = json.load(open(os.path.join(HERE, 'swap_c.json'), encoding='utf-8'))
by_gpio = {v[0]: n for n, v in pm['map'].items()}
sock = {int(k): v for k, v in pm['sock'].items()}
part = lambda spec, ref: next(p for p in spec['parts'] if p['ref'] == ref)

# ---- upper page 1: J601/J602 from the Plan C pin map, U608 (JY901S, user library part) ----
u1 = L('n1.json')
power = {(1, 39): 'GND', (1, 40): '5V_MAIN', (2, 37): 'GND', (2, 39): 'GND', (2, 40): '5V_MAIN'}
for h, ref in ((1, 'J601'), (2, 'J602')):
    p = part(u1, ref); nets, nc = {}, []
    for n in range(1, 41):
        net = power.get((h, n)) or by_gpio.get(sock[n + 40 * (h - 1)])
        if net: nets[str(n)] = net
        else: nc.append(str(n))
    p['nets'], p['nc'] = nets, nc
imu = part(L('n1_imu.json'), 'U608')
imu.update({'lib': '0819f05c4eef4c71ace90d822a990e87', 'uuid': 'e5c3754273754e7cbae712375e68caf4'})
u1['parts'].append(imu)

# ---- upper page 2: J603 slots + I2C pull-up pairs ----
u2 = L('n2.json')
j = part(u2, 'J603'); sig = set(C['j603'])
fixed = {k: v for k, v in j['nets'].items() if v in ('GND', '5V_LOGIC')}
j['nets'] = dict(fixed, **{str(v): k for k, v in C['j603'].items()})
j['nc'] = [str(n) for n in range(1, 41) if str(n) not in j['nets']]
assert j['nc'] == ['38'], j['nc']
PULL = [('R603', 'R604'), ('R632', 'R633'), ('R634', 'R635')]
BUS = {'I2C1': ('I2C_SCL', 'I2C_SDA'), 'I2C2': ('I2C2_SCL', 'I2C2_SDA'), 'I2C3': ('I2C3_SCL', 'I2C3_SDA')}
for b, (scl, sda) in BUS.items():
    rs, rd = PULL[C['pull'][b]]
    part(u2, rs)['nets'] = {'1': '3V3_MAIN', '2': scl}
    part(u2, rd)['nets'] = {'1': '3V3_MAIN', '2': sda}
# test points: the user's choice is the system-library Test-Point-0.5mm (1 x 1 mm pad), renumbered TP1-TP4
# (2026-11-03, set in the schematic by hand); RH-5015 / C5199798 pads now overlap at the 2.5 mm pitch
u2['parts'] = [p for p in u2['parts'] if not p['ref'].startswith('TP')] + [
    {'ref': r, 'lib': '0819f05c4eef4c71ace90d822a990e87', 'uuid': 'd45be48edf5f4f4eb9e20c75671b7f3b', 'x': x, 'y': 785,
     'nets': {'1': n}} for r, x, n in (('TP1', 280, '5V_MAIN'), ('TP2', 460, '3V3_MAIN'), ('TP3', 550, '3V3_RF'),
                                       ('TP4', 640, 'GND'))]

# ---- upper pages 3, 4: unchanged ----
u3, u4 = L('n3.json'), L('n4.json')

# ---- upper page 5: UART connectors / RX series resistors / Qwiic ----
u5 = L('n5.json')
for u, dest in C['udest'].items():
    if dest == 'LOWER': continue          # U4 = UART4 = step bus (USTEP_*) to the lower board
    part(u5, dest)['nets'] = {'1': '5V_MAIN', '2': u + '_TX', '3': u + '_RXD', '4': 'GND'}
    part(u5, C['ures'][u])['nets'] = {'1': u + '_RX', '2': u + '_RXD'}
for b, q in C['qw'].items():
    scl, sda = BUS[b]
    part(u5, q)['nets'] = {'1': 'GND', '2': '3V3_MAIN', '3': sda, '4': scl}; part(u5, q)['nc'] = ['5', '6']

# ---- lower: J513 mirrors J603 with odd/even pairs swapped; J513.37 keeps IMON ----
lows = [L(f'p{i}.json') for i in range(1, 7)]
j513 = part(lows[4], 'J513'); old = dict(j513['nets'])
mate = lambda n: n + 1 if n % 2 else n - 1
new = {str(mate(int(k))): v for k, v in j['nets'].items()}
new['37'] = old['37']
assert old['37'] == 'IMON', old['37']
for k, v in old.items():                      # power pins must already agree with the J603 mirror
    if v in ('GND', '5V_LOGIC'): assert new.get(k) == v, (k, v, new.get(k))
j513['nets'] = new; j513['nc'] = [str(n) for n in range(1, 41) if str(n) not in new]

for i, (s, pg) in enumerate(zip((u1, u2, u3, u4, u5), UP), 1):
    s.update(project=P, page=pg, name=f'c_u{i}'); save(f'c_u{i}.json', s)
for i, (s, pg) in enumerate(zip(lows, LO), 1):
    s.update(project=P, page=pg, name=f'c_l{i}'); save(f'c_l{i}.json', s)

# cross-board check: every J603 signal meets the same net on J513
bad = [(n, v, new.get(str(mate(int(n))))) for n, v in j['nets'].items() if new.get(str(mate(int(n)))) != v]
print('J603<->J513 mismatches:', bad, '| J513.37 =', new['37'], '| J513 nc =', j513['nc'])
print('parts per page: upper', [len(s['parts']) for s in (u1, u2, u3, u4, u5)], 'lower', [len(s['parts']) for s in lows])
